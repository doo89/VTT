export function getNestedTranslation(dict: TranslationDict, path: string): string {
  const keys = path.split('.');
  let current: TranslationDict | string = dict;
  for (const key of keys) {
    if (typeof current === 'string' || !current[key]) {
      return path;
    }
    current = current[key];
  }
  return typeof current === 'string' ? current : path;
}

export function useI18n(language: Language = 'fr') {
  const dict = translations[language] || translations.fr;

  const t = useCallback((key: string): string => {
    return getNestedTranslation(dict, key);
  }, [dict]);

  return { t, language };
}

export function getBrowserLanguage(): Language {
  const browserLang = navigator.language.toLowerCase();
  const supported: Language[] = ['fr', 'en', 'es', 'de', 'it', 'pt', 'ja', 'zh'];
  for (const lang of supported) {
    if (browserLang.startsWith(lang)) return lang;
  }
  return 'fr';
}
